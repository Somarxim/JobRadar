-- 复测方法：对齐 V6 探测时的请求形状（POST JSON + Referer），并做关键词矩阵
-- （含空格/无空格/乱码对照/表单编码/带 Cookie 与 Origin/GET 变体）。
--
-- 复测结论（2026-09-10）：
-- * 接口仍 200 且返回结构完整的 list，但 **kw 参数被静默忽略**——乱码词与
--   「校招Java」返回完全相同的通用热招列表（count 恒为 100）。所有请求形状变体
--   （form/GET/keyword 字段/cityId/Cookie）均一样。
-- * 判定：智联已把匿名搜索切为软反爬（大概率开始校验前端 JS 生成的 at/rt 令牌，
--   缺失时降级返回默认榜单而非 403）。V6「匿名可用」结论自此失效。
-- * 风险：这种软失败模式比 403 更危险——响应看似正常，若启用该源会把
--   「中药执业药师/车间生产主管」等无关岗位静默灌入岗位库。故保持禁用，
--   且启用前必须先加结果相关性护栏（如标题含查询词命中率校验）。
-- * 后续可选路线：① Playwright 带真实浏览器（与 51job 同一方案，可复用）；
--   ② 浏览器插件路线（用户在智联页面时由插件提取，天然带登录态与令牌）。

